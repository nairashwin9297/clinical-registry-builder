"""Generate the README's results section from the database, so the README never contains a typed-in number.

The section sits between RESULTS_START and RESULTS_END markers in README.md. `python manage.py
readme_results --write ../README.md` refreshes it; tests/test_readme.py fails if it is out of date.
"""

import re

from .format_utils import class_label

RESULTS_START = "<!-- results:start (generated by `python manage.py readme_results --write ../README.md`) -->"
RESULTS_END = "<!-- results:end -->"


def _pct(x, digits=0):
    return "–" if x is None else f"{x * 100:.{digits}f}%"


def _num(x):
    return "–" if x is None else f"{x:.2f}"


def results_markdown(metrics, models, prompt_version):
    o = metrics["procedures"]["overall"]
    lines = [
        f"Model: `{', '.join(models) or 'unknown'}`, prompt {prompt_version}, on {metrics['notes_scored']} notes. "
        "Procedure scores compare the model's answers with the **approximate** answer key.",
        "",
        "| Measure | Result |",
        "|---|---|",
        f"| Notes processed | {metrics['notes_processed']} ({metrics['notes_failed']} failed extraction) |",
        f"| Fields flagged for review | {metrics['fields_flagged']} of {metrics['fields_total']} "
        f"({_pct(metrics['flag_rate'], 1)}) |",
        f"| Notes with at least one flag | {metrics['notes_flagged']} ({_pct(metrics['notes_flagged_rate'])}) |",
        f"| Exact match (same set of procedure classes) | {o['exact_match']} of {o['notes']} "
        f"({_pct(o['exact_match_rate'])}) |",
        f"| Procedure precision / recall / F1 (micro) | {_num(o['micro_precision'])} / {_num(o['micro_recall'])} / "
        f"{_num(o['micro_f1'])} |",
        f"| Procedure macro F1 | {_num(o['macro_f1'])} |",
        "",
        "| Procedure class | In answer key | Predicted | Precision | Recall | F1 |",
        "|---|--:|--:|--:|--:|--:|",
    ]
    for r in metrics["procedures"]["per_class"]:
        lines.append(f"| {class_label(r['class_id'])} | {r['support']} | {r['predicted']} | {_num(r['precision'])} | "
                     f"{_num(r['recall'])} | {_num(r['f1'])} |")
    lines += ["", "Why fields were flagged:", ""]
    lines += [f"- {r['reason']}: {r['count']}" for r in metrics["flag_reasons"]]
    return "\n".join(lines)


def replace_section(readme_text, body):
    """Swap the text between the markers for `body`. Raises ValueError if the markers are missing."""
    pattern = re.compile(re.escape(RESULTS_START) + r".*?" + re.escape(RESULTS_END), re.DOTALL)
    if not pattern.search(readme_text):
        raise ValueError("README has no results markers")
    return pattern.sub(lambda _: f"{RESULTS_START}\n{body}\n{RESULTS_END}", readme_text)


def current_section(readme_text):
    m = re.search(re.escape(RESULTS_START) + r"\n(.*?)\n" + re.escape(RESULTS_END), readme_text, re.DOTALL)
    return m.group(1) if m else None
